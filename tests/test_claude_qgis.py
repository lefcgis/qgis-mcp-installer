def _cfg(base: Path, **kw) -> etl.Config:
    return etl.Config(base_dir=base, qgis_profile="auto", steps=set(etl.ALL_STEPS),
                      dry_run=False, non_interactive=True, skip_signature=False,
                      plugin_url="", **kw)


def _log(tmp: str) -> etl.Logger:
    return etl.Logger(Path(tmp) / "x.log", to_file=False)


def _fake_qgis(root: Path) -> Path:
    (root / "bin").mkdir(parents=True)
    (root / "bin" / "qgis-ltr-bin.exe").write_bytes(b"")
    return root


def _fake_claude(base: Path, version: str) -> None:
    (base / f"app-{version}").mkdir(parents=True, exist_ok=True)
    (base / f"app-{version}" / "claude.exe").write_bytes(b"")


class Claude(unittest.TestCase):
    def test_canal_oficial_toma_la_version_full_mas_alta(self):
        self.assertEqual(etl.parse_claude_feed(FEED_CLAUDE), "6.7000.0")
        self.assertIsNone(etl.parse_claude_feed(""))
        self.assertIsNone(etl.parse_claude_feed("basura\n<html>"))

    def test_setup_se_deriva_del_redirect_msix_y_solo_de_downloads_claude_ai(self):
        base = "https://downloads.claude.ai/releases/win32/x64/5.1/Claude-ab12.msix"
        self.assertEqual(etl.claude_setup_url_from_redirect(base),
                         "https://downloads.claude.ai/releases/win32/x64/5.1/Claude-ab12.exe")
        for malo in ("", "http://downloads.claude.ai/x/Claude-ab12.msix",
                     "https://evil.example.com/x/Claude-ab12.msix",
                     "https://downloads.claude.ai/x/Claude-ab12.exe",
                     "https://downloads.claude.ai.evil.com/x/Claude-ab12.msix"):
            self.assertIsNone(etl.claude_setup_url_from_redirect(malo), malo)

    def test_instalacion_por_usuario_exige_claude_exe_y_toma_la_mas_alta(self):
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp)
            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}):
                self.assertEqual(etl.claude_squirrel_install(), (None, None))
                base = local / "AnthropicClaude"
                (base / "app-9.9.9").mkdir(parents=True)  # residuo sin ejecutable
                self.assertEqual(etl.claude_squirrel_install(), (None, None))
                for v in ("5.11492.5", "6.6395.1", "6.7000.0"):
                    _fake_claude(base, v)
                ver, folder = etl.claude_squirrel_install()
                self.assertEqual(ver, "6.7000.0")
                self.assertEqual(folder, base / "app-6.7000.0")
                with mock.patch.object(etl, "_ps", return_value=(0, "", "")):
                    found, dver, _ = etl.detect_claude()
                self.assertTrue(found)
                self.assertEqual(dver, "6.7000.0")

    def test_claude_ya_instalado_y_vigente_no_descarga_nada(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            with mock.patch.object(etl, "detect_claude",
                                   return_value=(True, "6.6395.1", Path(tmp))), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "_install_claude_user") as inst, \
                 mock.patch.object(etl, "run_to_file") as ejec:
                self.assertTrue(etl.step1_claude_desktop(cfg, log))
            inst.assert_not_called()
            ejec.assert_not_called()

    def test_claude_por_usuario_vieja_se_actualiza_con_update_exe(self):
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp) / "L"
            base = local / "AnthropicClaude"
            _fake_claude(base, "5.11492.5")
            (base / "Update.exe").write_bytes(b"")
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)

            def update(cmd, log_, timeout, env=None):
                _fake_claude(base, "6.6395.1")
                return 0

            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "verify_signature", return_value=True), \
                 mock.patch.object(etl, "run_to_file", side_effect=update) as ejec:
                self.assertTrue(etl.step1_claude_desktop(cfg, log))
            self.assertEqual(ejec.call_count, 1)
            self.assertEqual([str(c) for c in ejec.call_args[0][0][1:]],
                             ["--update", manifest.CLAUDE_RELEASES_BASE])
            self.assertIn("6.6395.1", cfg.status[1])

    def test_instalacion_nueva_sin_admin_usa_setup_silencioso_y_actualiza_al_canal(self):
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp) / "L"
            base = local / "AnthropicClaude"
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            llamadas = []

            def ejecutar(cmd, log_, timeout, env=None):
                llamadas.append([Path(str(c)).name for c in cmd])
                if "--silent" in cmd:
                    _fake_claude(base, "5.11492.5")
                    (base / "Update.exe").write_bytes(b"")
                else:
                    _fake_claude(base, "6.6395.1")
                return 0

            setup = Path(tmp) / "Claude-xx.exe"
            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "_is_admin", return_value=False), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "resolve_claude_setup_url",
                                   return_value="https://downloads.claude.ai/r/5/Claude-xx.exe"), \
                 mock.patch.object(etl, "fetch_verified", return_value=setup), \
                 mock.patch.object(etl, "verify_signature", return_value=True), \
                 mock.patch.object(etl, "run_to_file", side_effect=ejecutar):
                self.assertTrue(etl.step1_claude_desktop(cfg, log))
            self.assertEqual(llamadas[0], ["Claude-xx.exe", "--silent"])
            self.assertEqual(llamadas[1], ["Update.exe", "--update", "x64"])
            self.assertNotIn(1, cfg.pending)
            self.assertIn("6.6395.1", cfg.status[1])
            self.assertEqual(cfg.warnings, [])

    def test_si_la_actualizacion_falla_queda_instalado_pero_con_advertencia(self):
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp) / "L"
            base = local / "AnthropicClaude"
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)

            def ejecutar(cmd, log_, timeout, env=None):
                if "--silent" in cmd:
                    _fake_claude(base, "5.11492.5")
                    (base / "Update.exe").write_bytes(b"")
                return 0  # Update.exe "termina" pero no deja la versión nueva

            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "resolve_claude_setup_url",
                                   return_value="https://downloads.claude.ai/r/5/Claude-xx.exe"), \
                 mock.patch.object(etl, "fetch_verified", return_value=Path(tmp) / "s.exe"), \
                 mock.patch.object(etl, "verify_signature", return_value=True), \
                 mock.patch.object(etl, "run_to_file", side_effect=ejecutar):
                self.assertTrue(etl.step1_claude_desktop(cfg, log))
            self.assertEqual(len(cfg.warnings), 1)  # no se reporta como «última»

    def test_si_no_se_puede_resolver_el_instalador_cae_a_la_guia_manual(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(Path(tmp) / "L")}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "claude_latest_version", return_value=None), \
                 mock.patch.object(etl, "resolve_claude_setup_url", return_value=None):
                self.assertTrue(etl.step1_claude_desktop(cfg, log))
            self.assertIn(1, cfg.pending)
            self.assertEqual(len(cfg.warnings), 1)

    def test_paso_7_rechaza_un_claude_con_firma_invalida(self):
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp) / "L"
            _fake_claude(local / "AnthropicClaude", "6.6395.1")
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "verify_signature", return_value=False):
                self.assertFalse(etl._verify_claude(cfg, log))
            with mock.patch.dict(os.environ, {"LOCALAPPDATA": str(local)}), \
                 mock.patch.object(etl, "_ps", return_value=(0, "", "")), \
                 mock.patch.object(etl, "claude_latest_version", return_value="6.6395.1"), \
                 mock.patch.object(etl, "verify_signature", return_value=True):
                self.assertTrue(etl._verify_claude(cfg, log))


class QgisSerie(unittest.TestCase):
    def test_serie_344(self):
        self.assertEqual(manifest.QGIS_SERIES, (3, 44))
        self.assertTrue(etl.qgis_in_series(manifest.QGIS_VERSION))
        self.assertTrue(etl.qgis_in_series("3.44.9"))
        for otra in ("3.40.15", "3.4.4", "3.440.1", "4.2.3", "", None):
            self.assertFalse(etl.qgis_in_series(otra), otra)

    def test_setup_ini_toma_la_version_vigente_no_la_prev(self):
        self.assertEqual(etl.parse_osgeo4w_ini(SETUP_INI, "qgis-ltr"), "3.44.15-1")
        # `qgis` a secas ya es la serie 4: nunca debe confundirse con el LTR
        self.assertEqual(etl.parse_osgeo4w_ini(SETUP_INI, "qgis"), "4.2.3-1")
        self.assertIsNone(etl.parse_osgeo4w_ini(SETUP_INI, "no-existe"))

    def test_indice_de_msi_elige_el_ultimo_parche_de_3_44_en_orden_numerico(self):
        self.assertEqual(etl.latest_msi_in_index(INDEX_QGIS), ("3.44.15", "2"))
        self.assertIsNone(etl.latest_msi_in_index("QGIS-OSGeo4W-4.2.3-2.msi"))
        self.assertIsNone(etl.latest_msi_in_index(""))

    def test_version_desde_la_base_de_paquetes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            db = root / "etc" / "setup" / "installed.db"
            db.parent.mkdir(parents=True)
            db.write_text("INSTALLED.DB 8\ngdal gdal-3.13.3-1.tar.bz2 0\n"
                          "qgis-ltr qgis-ltr-3.44.15-1.tar.bz2 0\n", encoding="utf-8")
            self.assertEqual(etl._qgis_version_from_db(root), "3.44.15")

    def test_un_qgis_de_otra_serie_no_cuenta_como_3_44(self):
        with tempfile.TemporaryDirectory() as tmp:
            pf = Path(tmp) / "PF"
            _fake_qgis(pf / "QGIS 4.2.3")
            with mock.patch.dict(os.environ, {"ProgramFiles": str(pf)}), \
                 mock.patch.object(etl, "read_qgis_version",
                                   side_effect=lambda d, fresh=False: "4.2.3"):
                self.assertFalse(etl.detect_qgis_ltr()[0])
                self.assertEqual(etl.detect_qgis()[1], "4.2.3")
                # y el paso 7 no lo da por bueno
                self.assertFalse(etl._verify_qgis_series(_cfg(Path(tmp) / "raiz"), _log(tmp)))

    def test_con_3_44_y_4_x_a_la_vez_gana_la_3_44(self):
        with tempfile.TemporaryDirectory() as tmp:
            pf = Path(tmp) / "PF"
            _fake_qgis(pf / "QGIS 4.2.3")
            _fake_qgis(pf / "QGIS 3.44.15")
            vers = {"QGIS 4.2.3": "4.2.3", "QGIS 3.44.15": "3.44.15"}
            with mock.patch.dict(os.environ, {"ProgramFiles": str(pf)}), \
                 mock.patch.object(etl, "read_qgis_version",
                                   side_effect=lambda d, fresh=False: vers[d.name]):
                found, ver, path = etl.detect_qgis_ltr()
                self.assertEqual((found, ver, path.name), (True, "3.44.15", "QGIS 3.44.15"))
                cfg = _cfg(Path(tmp) / "raiz")
                self.assertTrue(etl._verify_qgis_series(cfg, _log(tmp)))
                self.assertEqual(cfg.qgis_version, "3.44.15")

    def test_carpeta_sin_ejecutable_no_es_una_instalacion(self):
        with tempfile.TemporaryDirectory() as tmp:
            pf = Path(tmp) / "PF"
            (pf / "QGIS 3.44.12" / "bin").mkdir(parents=True)
            with mock.patch.dict(os.environ, {"ProgramFiles": str(pf)}):
                self.assertFalse(etl.detect_qgis_ltr()[0])

    def test_paso_2_con_solo_qgis_4_instala_la_3_44(self):
        with tempfile.TemporaryDirectory() as tmp:
            pf = Path(tmp) / "PF"
            _fake_qgis(pf / "QGIS 4.2.3")
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            with mock.patch.dict(os.environ, {"ProgramFiles": str(pf)}), \
                 mock.patch.object(etl, "read_qgis_version",
                                   side_effect=lambda d, fresh=False: "4.2.3"), \
                 mock.patch.object(etl, "_is_admin", return_value=False), \
                 mock.patch.object(etl, "_install_qgis_user", return_value=True) as inst:
                self.assertTrue(etl.step2_qgis(cfg, log))
            inst.assert_called_once()

    def test_osgeo4w_que_ya_sirve_otra_serie_no_se_instala(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            with mock.patch.object(etl, "fetch_verified", return_value=Path(tmp) / "setup.exe"), \
                 mock.patch.object(etl, "osgeo4w_ltr_version", return_value="3.48.0-1"), \
                 mock.patch.object(etl, "run") as ejec:
                self.assertFalse(etl._install_qgis_user(cfg, log))
            ejec.assert_not_called()

    def test_tras_instalar_la_version_del_binario_manda(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)
            self.assertFalse(etl._confirm_series(cfg, log, "4.2.3", Path(tmp)))
            self.assertFalse(etl._confirm_series(cfg, log, None, Path(tmp)))
            self.assertIsNone(cfg.qgis_version)
            self.assertTrue(etl._confirm_series(cfg, log, "3.44.15", Path(tmp)))
            self.assertEqual(cfg.qgis_version, "3.44.15")

    def test_instalacion_propia_con_parche_viejo_se_actualiza_y_ajena_solo_avisa(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg, log = _cfg(Path(tmp) / "raiz"), _log(tmp)

            def reinstalar(c, l):
                c.qgis_version = "3.44.15"
                return True

            with mock.patch.object(etl, "osgeo4w_ltr_version", return_value="3.44.15-1"), \
                 mock.patch.object(etl, "qgis_running", return_value=False), \
                 mock.patch.object(etl, "_install_qgis_user", side_effect=reinstalar) as inst:
                self.assertEqual(
                    etl._maybe_upgrade_qgis(cfg, log, "3.44.12", cfg.user_qgis_root), "3.44.15")
                inst.assert_called_once()
                inst.reset_mock()
                self.assertEqual(
                    etl._maybe_upgrade_qgis(cfg, log, "3.44.12",
                                            Path(tmp) / "PF" / "QGIS 3.44.12"), "3.44.12")
                self.assertEqual(
                    etl._maybe_upgrade_qgis(cfg, log, "3.44.15", cfg.user_qgis_root), "3.44.15")
                inst.assert_not_called()


